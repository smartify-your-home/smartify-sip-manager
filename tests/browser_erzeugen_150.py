from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(args=['--no-sandbox'])
    pg = b.new_context(bypass_csp=True, viewport={'width': 1330, 'height': 1000}).new_page()
    errs = []; pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('dialog', lambda d: d.accept())
    pg.goto('http://127.0.0.1:8099/')
    pg.wait_for_selector('.pb-group')
    pg.click('[data-tab="anlage"]')
    pg.wait_for_function("document.getElementById('anState').textContent.includes('Modell')")
    pg.click('#anVorschlag'); pg.wait_for_selector('#anRows tr[data-i="4"]')
    pg.fill('#anName', 'Haus Pfaffstätt'); pg.fill('#anLan', '127.0.0.1')
    pg.fill('#anHttps', 'https://homeassistant.example-tailnet.ts.net:8443')
    row = pg.locator('#anRows tr', has=pg.locator('input[data-k="nummer"][value="104"]'))
    row.locator('[data-f="ios"]').check(); row.locator('[data-f="video_im_anruf"]').check()
    row = pg.locator('#anRows tr', has=pg.locator('input[data-k="endpoint"][value="linphone-cloud"]'))
    row.locator('[data-f="video_im_anruf"]').check()
    # Kamera suchen
    pg.click('#kamSuche'); pg.wait_for_selector('#kamRows tr[data-k="0"] .kam-test', timeout=60000)
    r = pg.locator('#kamRows tr[data-k="0"]')
    print('gefunden:', r.inner_text()[:120].replace('\n',' | '))
    r.locator('[data-f="benutzer"]').fill('admin'); r.locator('[data-f="passwort"]').fill('richtig'); r.locator('[data-f="stream"]').fill('einfahrt')
    r.locator('.kam-test').click(); pg.wait_for_selector('#kamRows .kam-res .lv-ok', timeout=10000)
    pg.locator('#kamRows tr[data-k="0"] .kam-add').click()
    pg.wait_for_selector('#anRows input[data-k="stream"][value="einfahrt"]')
    pg.click('#anSave'); pg.wait_for_function("document.getElementById('anState').textContent==='Gespeichert'")
    pg.screenshot(path='15_anlage.png', full_page=True)
    pg.click('[data-tab="erzeugen"]'); pg.wait_for_selector('.erz-ziel')
    pg.screenshot(path='15_vorschau.png', full_page=True)
    print(pg.inner_text('#erzZiele')[:1800])
    pg.click('#erzApply'); pg.wait_for_selector('#erzResult .note')
    print('ERGEBNIS:', pg.inner_text('#erzResult'))
    pg.click('[data-tab="start"]'); pg.click('#pbRun'); pg.wait_for_timeout(1500)
    print('PRUEF:', pg.inner_text('#pbSum'))
