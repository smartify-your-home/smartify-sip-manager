    pg.screenshot(path='15_pruef.png', full_page=True)
    pg.click('[data-tab="anlage"]'); pg.click('[data-tab="erzeugen"]'); pg.wait_for_timeout(800)
    print('ZWEITE VORSCHAU:', pg.inner_text('#erzState'))
    print('ERRORS', errs); b.close()
