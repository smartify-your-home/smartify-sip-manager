"""Tests für „AMI-Zugang einrichten“ (v1.7)."""
import importlib.util, json, os, tempfile, unittest
from pathlib import Path
from unittest import mock

TMP = Path(tempfile.mkdtemp(prefix='smartify-170-'))
os.environ['SMARTIFY_DATA_DIR'] = str(TMP / 'data')
os.environ['ADDON_CONFIGS_ROOT'] = str(TMP / 'configs')
AST = TMP / 'configs' / '3e533915_asterisk' / 'asterisk'
(AST / 'custom').mkdir(parents=True)
(AST / 'default').mkdir(parents=True)
(AST / 'default' / 'manager.conf').write_text('; THIS FILE IS AUTO-GENERATED BY THE ADD-ON!\n[general]\nenabled = yes\nport = 5038\n\n[admin]\nsecret = test1234\ndeny = 0.0.0.0/0.0.0.0\npermit = 127.0.0.1/255.255.255.0\n')
spec = importlib.util.spec_from_file_location('app170', Path(__file__).resolve().parents[1] / 'smartify_sip_manager' / 'app.py')
app = importlib.util.module_from_spec(spec)
spec.loader.exec_module(app)
(TMP / 'data' / 'options.json').write_text(json.dumps({'ami_host': '192.168.2.65', 'ami_username': 'admin', 'ami_password': 'alt'}))


class AmiTests(unittest.TestCase):
    def test_block_insert_replace_refuse(self):
        a = app.manager_conf_with_user('[other]\nsecret=1\n', 'pw1')
        self.assertIn('[other]', a)
        self.assertIn('secret = pw1', a)
        self.assertIn('permit = 172.30.32.0/255.255.254.0', a)
        b = app.manager_conf_with_user(a, 'pw2')
        self.assertEqual(b.count('[smartify]'), 1)
        self.assertIn('secret = pw2', b)
        self.assertNotIn('pw1', b)
        with self.assertRaisesRegex(ValueError, 'eigenen Abschnitt'):
            app.manager_conf_with_user('[smartify]\nsecret=meins\n', 'pw')

    def test_einrichten(self):
        self.maxDiff = None
        with self.assertRaisesRegex(ValueError, 'Bestätigung'):
            app.ami_einrichten({})
        with mock.patch.object(app, 'self_options_update', return_value=True) as upd:
            r = app.ami_einrichten({'confirm': True})
        self.assertTrue(r['eingerichtet'])
        self.assertTrue(r['manager_conf'])
        self.assertTrue(r['neustart_noetig'])
        main = (AST / 'custom' / 'manager.conf').read_text()
        self.assertIn('secret = test1234', main, '[admin] bleibt unverändert')
        self.assertIn('permit = 127.0.0.1/255.255.255.0', main)
        self.assertTrue(main.rstrip().endswith('#tryinclude manager_custom.conf'))
        self.assertTrue(app.manager_include_state())
        with mock.patch.object(app, 'self_options_update', return_value=True):
            r2 = app.ami_einrichten({'confirm': True})
        self.assertFalse(r2['manager_conf'], 'zweites Mal: Einbindung schon da')
        self.assertIn('manager reload', r2['befehl'])
        self.assertEqual((AST / 'custom' / 'manager.conf').read_text().count('#tryinclude'), 1)
        conf = (AST / 'custom' / 'manager_custom.conf').read_text()
        pw = json.loads(app.AMI_OVERRIDE_FILE.read_text())['ami_password']
        self.assertIn(f'secret = {pw}', conf)
        self.assertGreaterEqual(len(pw), 30)
        opts = app.get_options()
        self.assertEqual((opts['ami_username'], opts['ami_password'], opts['ami_host']), ('smartify', pw, '192.168.2.65'))
        self.assertEqual(upd.call_args[0][0]['ami_username'], 'smartify')

    def test_report_offers_button(self):
        rep = app.anlage_model.pruefbericht(app.anlage_model.leer(), {'asterisk_dir': True, 'sip_core': {}, 'streams': {},
                                                                       'ami_error': 'AMI-Anmeldung verweigert: Authentication failed'})
        row = next(r for r in rep['zeilen'] if r['titel'].startswith('AMI'))
        self.assertEqual((row['level'], row['aktion']), ('warn', 'ami_einrichten'))


if __name__ == '__main__':
    unittest.main()
